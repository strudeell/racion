// Все рецепты собираются здесь из трёх файлов в папке recipes/.
//
// Как добавить рецепт: скопируйте любой рецепт в нужном файле, поменяйте id
// (латиницей, без повторов) и остальные поля.
//
// Поля рецепта:
//   id     — уникальный код латиницей
//   name   — название блюда
//   emoji  — картинка-эмодзи
//   meals  — когда подавать: ['breakfast'], ['lunch'], ['dinner'] или несколько
//   time   — время готовки, минут
//   equip  — нужная техника: stove, oven, micro, multicooker, airfryer, blender,
//            steamer, grillpan, waffle. «|» значит «или», «+» — «и».
//            'stove|multicooker + blender' — плита или мультиварка, и ещё блендер.
//            Пустая строка — техника не нужна.
//   batch  — 2, если блюдо готовят сразу на 2 дня (супы, рагу)
//   kid    — false, если блюдо не подходит детям
//   spicy  — true, если блюдо острое само по себе
//   summer — true, если блюдо летнее (окрошка, гаспачо): предлагается только с мая по сентябрь
//   kind   — группа похожих блюд, если её не понять по первому слову названия:
//            гороховый и чечевичный супы — оба 'бобовый'. Похожие блюда в одно меню ставятся реже.
//   ing    — продукты на ОДНУ взрослую порцию: [код продукта, количество]
//            или [код, количество, 'opt'] — «по желанию»: если продукт нельзя,
//            его просто уберут, а блюдо останется.
//            Количество — в единицах продукта (г, мл, шт) из products.js.
//   steps  — шаги приготовления

